import { routeSchema } from "../../packages/route-schema";
const state = (
  id: string,
  pathname: string,
  heading: string,
  behavior: "navigate" | "boundary" | "checkpoint" | "success" = "navigate",
  modal = false,
) => ({
  id,
  urlPatterns: [pathname],
  landmarks: [{ role: "heading", names: [heading], required: true }],
  minimumConfidence: 0.8,
  behavior,
  modal,
});
const step = (
  id: string,
  from: string,
  to: string[],
  name: string[],
  instruction: string,
  role = "button",
) => ({
  id,
  from,
  to,
  actor: "user" as const,
  risk: "navigation" as const,
  target: {
    role,
    names: name,
    context: "Subscription",
    disallowedNearbyText: ["Delete account", "Confirm cancellation"],
    minimumConfidence: 0.8,
  },
  instruction,
  timeoutMs: 8000,
});
